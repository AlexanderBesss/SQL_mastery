import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = process.cwd();
const tracks = [
  { id: 'schema', name: 'Schema Design', eyebrow: 'Foundation', description: 'Relationships, constraints, types, temporal data, and normalization.', dir: 'schema_design', color: 'mint' },
  { id: 'architecture', name: 'Architecture', eyebrow: 'Production blueprints', description: 'Complete schemas for commerce, SaaS, booking, social systems, events, and ledgers.', dir: 'architecture_solutions', color: 'amber' },
  { id: 'advanced', name: 'Advanced PostgreSQL', eyebrow: 'Deep systems', description: 'Indexes, query plans, concurrency, partitioning, security, operations, and recovery.', dir: 'advanced_patterns', color: 'violet' },
  { id: 'interview', name: 'Node.js Interview Lab', eyebrow: 'Applied practice', description: 'Backend interview questions, failure modes, and production-ready answers.', dir: 'interview_sql_nodejs', color: 'coral' },
];

const cleanTitle = (value) => value.replace(/^PATTERN \d+:\s*/i, '').replace(/^ADVANCED PATTERN \d+:\s*/i, '').replace(/^Solution \d+:\s*/i, '').trim().replace(/\b\w/g, c => c.toUpperCase());
const plain = (value) => value.replace(/```[\s\S]*?```/g, ' ').replace(/`([^`]+)`/g, '$1').replace(/!?(?:\[([^\]]*)\])\([^)]*\)/g, '$1').replace(/[*_>#|]/g, ' ').replace(/\s+/g, ' ').trim();
const slug = (value) => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const lessons = [];
for (const track of tracks) {
  const files = readdirSync(join(root, track.dir)).filter(file => /^\d+.*\.md$/.test(file)).sort();
  files.forEach((file, index) => {
    const markdown = readFileSync(join(root, track.dir, file), 'utf8').replace(/\r\n/g, '\n');
    const heading = markdown.match(/^#\s+(.+)$/m)?.[1] ?? file.replace(/\.md$/, '');
    const title = cleanTitle(heading);
    const bodyWithoutTitle = markdown.replace(/^#\s+.+\n+/, '');
    const firstParagraph = bodyWithoutTitle.split(/\n\s*\n/).map(plain).find(text => text.length > 45 && !text.startsWith('CREATE ') && !text.startsWith('|'));
    const sectionTitles = [...markdown.matchAll(/^##\s+(.+)$/gm)].map(match => plain(match[1])).filter(Boolean);
    const codeBlocks = [...markdown.matchAll(/```(?:sql|javascript|js|typescript|ts)?\s*\n([\s\S]*?)```/g)].length;
    const questionCount = [...markdown.matchAll(/^##\s+Q\d+:/gm)].length;
    const wordCount = plain(markdown).split(/\s+/).filter(Boolean).length;
    lessons.push({
      id: `${track.id}-${slug(file.replace(/^\d+[_-]?|\.md$/g, ''))}`,
      order: index + 1,
      trackId: track.id,
      title,
      summary: firstParagraph ?? `A practical guide to ${title.toLowerCase()} in PostgreSQL.`,
      minutes: Math.max(5, Math.round(wordCount / 190)),
      sectionTitles,
      codeBlocks,
      questionCount,
      source: relative(root, join(root, track.dir, file)).replaceAll('\\', '/'),
      markdown,
    });
  });
}

const payload = `// Generated by scripts/generate-content.mjs — do not edit by hand.\nexport const tracks = ${JSON.stringify(tracks, null, 2)} as const;\nexport const lessons = ${JSON.stringify(lessons, null, 2)} as const;\n`;
mkdirSync(join(root, 'app', 'content'), { recursive: true });
writeFileSync(join(root, 'app', 'content', 'generated.ts'), payload);
console.log(`Generated ${lessons.length} lessons across ${tracks.length} learning tracks.`);
